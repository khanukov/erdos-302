#!/usr/bin/env python3
"""Generate independent kernel-checked capacity declarations for vertices 3–10."""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

def render(v):
    return f'''-- Generated by scripts/generate_pack1094_batch.py; do not edit.
import Pack1094

open Finset UpperBridge
open scoped BigOperators

namespace ArchivePack1094

-- This check uses the original full index set, row sets and weights.
set_option maxRecDepth 65536 in
set_option maxHeartbeats 0 in
theorem capacity_vertex_{v} :
    (∑ i ∈ indices.filter (fun i => {v} ∈ T i), w i) ≤ 1000 := by
  decide

-- Verify that this is an actual declared support vertex, not a vacuous check.
set_option maxRecDepth 65536 in
set_option maxHeartbeats 0 in
theorem support_vertex_{v} : {v} ∈ support := by
  decide

-- Type-level regression test: explicitly instantiate the original definitions.
example : (∑ i ∈ ArchivePack1094.indices.filter
    (fun i => {v} ∈ ArchivePack1094.T i), ArchivePack1094.w i) ≤ 1000 :=
  capacity_vertex_{v}

#print axioms capacity_vertex_{v}
#print axioms support_vertex_{v}
end ArchivePack1094
'''

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    stale = []
    for v in range(3, 11):
        path = ROOT / 'lean' / f'Pack1094Vertex{v}.lean'
        text = render(v)
        if args.check:
            if not path.exists() or path.read_text() != text:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(text)
    if stale:
        print('Missing or stale generated files:', ', '.join(stale))
        return 1
    return 0

if __name__ == '__main__':
    raise SystemExit(main())
