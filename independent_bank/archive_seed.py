#!/usr/bin/env python3
"""Reproduce the literal Lean fixture for node zero of the pinned bank.

This binds a transcription to source bytes; it does not prove byte parsing in Lean.
"""
import hashlib
import lzma
from pathlib import Path

from replay_inventory import parse_json

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'audit/source/erdos302_boundary_certificates/baseline/bank.json.xz'
TARGET = ROOT / 'lean/ArchiveSeedNode0.lean'
SHA256 = '5c1a1fa4edcc1a0bc7ac3fc9cd3bc7fca4eedad6cb689b6540436ca35ed89034'


def load_first_node(raw=None):
    if raw is None:
        raw = SOURCE.read_bytes()
    if hashlib.sha256(raw).hexdigest() != SHA256:
        raise ValueError('source SHA-256 mismatch')
    bank = parse_json(lzma.decompress(raw))
    if not isinstance(bank, dict) or bank.get('schema') != 'erdos302-standalone-finite-proof-bank-v1':
        raise ValueError('bank schema')
    return bank['nodes'][0]


def render(node):
    if (type(node) is not dict or set(node) != {'t', 'v', 'r'} or node['t'] != 'small'
            or type(node['v']) is not list or not node['v']
            or any(type(x) is not int or x <= 0 for x in node['v'])
            or node['v'] != sorted(set(node['v']))
            or type(node['r']) is not int or node['r'] < 0):
        raise ValueError('unsupported node')
    values = ', '.join(map(str, node['v']))
    return f'''import BankProfile

/- Generated by independent_bank/archive_seed.py from pinned bank node 0.
The source-byte correspondence is checked outside Lean. -/
namespace ArchiveSeedNode0

def nodes : ℕ → ArchiveDag.Node
  | 0 => ⟨{{{values}}}, {node['r']}, .small⟩
  | _ => ⟨∅, 0, .small⟩

end ArchiveSeedNode0
'''


if __name__ == '__main__':
    import sys
    expected = render(load_first_node())
    if sys.argv[1:] == ['--write']:
        TARGET.write_text(expected)
    elif sys.argv[1:] == []:
        if TARGET.read_text() != expected:
            raise SystemExit('generated Lean source differs from pinned bank')
        print('node 0 matches pinned bank source')
    else:
        raise SystemExit('usage: archive_seed.py [--write]')
