#!/usr/bin/env python3
"""Generate a bounded first-eight-row candidate from the pinned bank replay."""
from pathlib import Path
import node1209_closure
import node1209_pack_preflight

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'lean/Node1209PackPilot.lean'

def rows():
    doc = node1209_closure.extract()
    node1209_pack_preflight.check(doc)
    root = doc['nodes'][-1]
    result = []
    for (image, weight), ref in zip(root['raw_node']['rows'][:8], root['references'][:8]):
        source = doc['nodes'][ref['dense_source']]
        if (ref['original_source'] != 0 or source['raw_node'] != {'t': 'small', 'v': [2, 3, 6], 'r': 1}
                or source['support'] != [2, 3, 6] or source['demand'] != 1):
            raise ValueError('pilot source differs from literal node 0')
        result.append(dict(ref, image=image, weight=weight))
    return result

def generate():
    rs = rows()
    support = node1209_closure.extract()['nodes'][-1]['support']
    row_literal = ', '.join('⟨{original_source}, {mul}, {div}, {weight}⟩'.format(**r) for r in rs)
    image_ids = ', '.join(str(r['image']) for r in rs)
    literal = ', '.join(map(str, support))
    return f'''-- Generated from the authenticated root pack; not a full pack proof.
import Dag
import MixedDag

open Finset UpperBridge
namespace Node1209PackPilot

set_option maxRecDepth 65536
set_option maxHeartbeats 100000000

def imageIds : Fin 8 → ℕ := ![{image_ids}]
def rows : Fin 8 → MixedDag.Row := ![{row_literal}]
def source : Finset ℕ := {{2, 3, 6}}
def target : Finset ℕ := {{{literal}}}

/-- Exact bounded row obligations for the first eight occurrences. -/
def RowCheck (i : Fin 8) : Prop :=
  (rows i).source = 0 ∧ (rows i).source < 1209 ∧
  0 < (rows i).mul ∧ 0 < (rows i).div ∧
  (∀ x ∈ source, (rows i).div ∣ x * (rows i).mul) ∧
  ArchiveScaling.image source (rows i).mul (rows i).div ⊆ target

instance (i : Fin 8) : Decidable (RowCheck i) := by
  unfold RowCheck
  infer_instance

theorem source_checked : ArchiveDag.SmallCheck source 1 := by decide

theorem rows_checked : ∀ i : Fin 8, RowCheck i := by decide

/-- These are genuine row bounds, but only for the first eight occurrences. -/
theorem row_bounds (i : Fin 8) :
    Extended.Bound (ArchiveScaling.image source (rows i).mul (rows i).div) 1 := by
  obtain ⟨_, _, hm, hd, hex, _⟩ := rows_checked i
  exact ArchivePack.scaled_bound hm hd hex (ArchiveDag.small_sound source_checked)

#print axioms source_checked
#print axioms rows_checked
#print axioms row_bounds
end Node1209PackPilot
'''

def matches(data):
    return data == generate().encode('utf-8')

def main():
    import sys
    node1209_closure.verify()
    data = generate().encode('utf-8')
    if sys.argv[1:] == ['--write']:
        OUTPUT.write_bytes(data)
    elif sys.argv[1:] == ['--check']:
        if OUTPUT.read_bytes() != data:
            raise SystemExit('pilot bytes differ from pinned input')
    else:
        raise SystemExit('use --write or --check')
    print('First eight root pack rows: exact generated bytes match')

if __name__ == '__main__':
    main()
