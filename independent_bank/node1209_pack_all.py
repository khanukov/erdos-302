#!/usr/bin/env python3
"""Generate occurrence-preserving, bounded node 1209 row-check candidates."""
from pathlib import Path
import sys
import node1209_closure
import node1209_pack_preflight

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'lean/node1209-pack-all'
SIZE = 8

def lit(xs):
    return '{' + ', '.join(map(str, xs)) + '}'

def generate():
    doc = node1209_closure.extract()
    node1209_pack_preflight.check(doc)
    root = doc['nodes'][-1]
    rows = []
    for i, ((image, weight), ref) in enumerate(zip(root['raw_node']['rows'], root['references'])):
        node = doc['nodes'][ref['dense_source']]
        rows.append(dict(index=i, image=image, weight=weight, source=ref['original_source'],
                         mul=ref['mul'], div=ref['div'], support=node['support'], demand=node['demand']))
    files = {}
    for batch in range((len(rows)+SIZE-1)//SIZE):
        group = rows[batch*SIZE:(batch+1)*SIZE]
        name = f'Node1209Rows{batch:03d}'
        lines = ['-- Generated; occurrences are not deduplicated.', 'import Dag', 'import MixedDag',
                 'open Finset UpperBridge', f'namespace {name}', 'set_option maxRecDepth 65536',
                 'set_option maxHeartbeats 100000000', f'def target : Finset ℕ := {lit(root["support"])}']
        for r in group:
            i = r['index']
            lines += [f'def imageId{i} : ℕ := {r["image"]}',
                      f'def row{i} : MixedDag.Row := ⟨{r["source"]}, {r["mul"]}, {r["div"]}, {r["weight"]}⟩',
                      f'def source{i} : Finset ℕ := {lit(r["support"])}',
                      f'def Check{i} : Prop := (row{i}).source < 1209 ∧ 0 < (row{i}).mul ∧ 0 < (row{i}).div ∧ (∀ x ∈ source{i}, (row{i}).div ∣ x * (row{i}).mul) ∧ ArchiveScaling.image source{i} (row{i}).mul (row{i}).div ⊆ target',
                      f'instance : Decidable Check{i} := by unfold Check{i}; infer_instance',
                      f'theorem check{i} : Check{i} := by decide',
                      f'theorem bound{i} (h : Extended.Bound source{i} {r["demand"]}) : Extended.Bound (ArchiveScaling.image source{i} (row{i}).mul (row{i}).div) {r["demand"]} := by',
                      f'  obtain ⟨_, hm, hd, hex, _⟩ := check{i}',
                      '  exact ArchivePack.scaled_bound hm hd hex h',
                      f'#print axioms check{i}', f'#print axioms bound{i}']
        lines += [f'end {name}', '']
        files[name+'.lean'] = '\n'.join(lines).encode()
    # Conditional assembly: the propositions are the exact checks in the shard modules.
    imports = [f'import Node1209Rows{n:03d}' for n in range((len(rows)+SIZE-1)//SIZE)]
    checks = [f'Node1209Rows{i//SIZE:03d}.Check{i}' for i in range(len(rows))]
    proofs = [f'Node1209Rows{i//SIZE:03d}.check{i}' for i in range(len(rows))]
    assembly = imports + ['namespace Node1209RowsAll', 'set_option maxRecDepth 65536',
        'theorem checks : ' + ' ∧\n  '.join(checks) + ' := by',
        '  exact ⟨' + ', '.join(proofs) + '⟩', '#print axioms checks', 'end Node1209RowsAll', '']
    files['Node1209RowsAll.lean'] = '\n'.join(assembly).encode()
    return {'rows': rows, 'files': files}

def check_files(data, files):
    if files.keys() != data['files'].keys():
        raise ValueError('generated file inventory differs')
    for name, expected in data['files'].items():
        if files[name] != expected:
            raise ValueError(f'generated bytes differ: {name}')

def main():
    node1209_closure.verify()
    data = generate()
    if sys.argv[1:] == ['--write']:
        OUT.mkdir(parents=True, exist_ok=True)
        for name, content in data['files'].items(): (OUT / name).write_bytes(content)
    elif sys.argv[1:] == ['--check']:
        check_files(data, {p.name: p.read_bytes() for p in OUT.glob('*.lean')})
    else:
        raise SystemExit('use --write or --check')
    print(f'{len(data["rows"])} occurrences, {len(data["files"])-1} shards, one assembly: exact bytes')

if __name__ == '__main__': main()
