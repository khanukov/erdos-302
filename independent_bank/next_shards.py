#!/usr/bin/env python3
"""Reproducibly transcribe and check the first 32 actual bank nodes.

The generated Lean checks literals; correspondence with archive bytes is a
Python check, not a theorem in Lean. Nodes outside 0..31 are explicit defaults.
"""
import argparse
import pathlib
import re

import archive_prefix
import mixed_lean_producer
import mixed_prefix_export

OUT = pathlib.Path(__file__).resolve().parents[1] / 'audit/shard-aggregation'
RANGES = ((0, 9), (9, 16), (16, 32))


def generate():
    doc = mixed_prefix_export.export(archive_prefix.load_bank())
    rendered = mixed_lean_producer.render(doc)
    rows = re.findall(r'^  \| (\d+) => (.+)$', rendered, re.MULTILINE)
    if len(rows) != 1091 or any(int(i) != n for n, (i, _) in enumerate(rows)):
        raise ValueError('unexpected rendered node inventory')
    result = {}
    result['ActualPrefix32Data.lean'] = (
        'import MixedCaseTrimCandidate\n\n'
        '/- Generated actual nodes 0..31; archive correspondence is not a Lean theorem. -/\n'
        'namespace ActualPrefix32Data\nopen MixedCaseTrimCandidate\n'
        'def nodes : ℕ → MixedDag.Node Payload\n' +
        ''.join(f'  | {i} => {row}\n' for i, row in rows[:32]) +
        '  | _ => ⟨∅, 0, .small⟩\nend ActualPrefix32Data\n')
    for shard, (start, end) in enumerate(RANGES):
        parts = ['import ActualPrefix32Data\n', 'namespace ActualPrefix32\n',
                 'open ActualPrefix32Data MixedCaseTrimCandidate\n',
                 'set_option maxRecDepth 4096\nset_option maxHeartbeats 4000000\n']
        for i in range(start, end):
            kind = doc['nodes'][i]['kind']
            if kind == 'case_placeholder':
                proof = ('by\n  change CaseCheck nodes ' + str(i) + ' _ _\n'
                         '  unfold CaseCheck RefCheck row image nodes\n'
                         '  decide')
            elif kind == 'trim_placeholder':
                proof = (f'by\n  change TrimCheck nodes {i} _\n'
                         '  unfold TrimCheck RefCheck image nodes UpperBridge.OrderedEdge\n'
                         '  decide')
            elif kind in ('basic', 'pack'):
                proof = 'by decide'
            else:
                raise ValueError(f'unsupported shard rule {kind}')
            parts.append(f'theorem check{i} : MixedDag.Check extraCheck nodes {i} := {proof}\n')
        parts.extend(f'#print axioms check{i}\n' for i in range(start, end))
        parts.append('end ActualPrefix32\n')
        result[f'ActualPrefix32Checks{shard}.lean'] = ''.join(parts)
    lines = [*(f'import ActualPrefix32Checks{i}\n' for i in range(len(RANGES))),
             '\nnamespace ActualPrefix32\nopen ActualPrefix32Data MixedCaseTrimCandidate\n',
             'theorem checked : ∀ i < 32, MixedDag.Check extraCheck nodes i := by\n',
             '  intro i hi\n  interval_cases i <;> first | ',
             ' | '.join(f'exact check{i}' for i in range(32)), '\n',
             'theorem sound : ∀ i < 32, Extended.Bound (nodes i).support (nodes i).demand :=\n',
             '  MixedCaseTrimCandidate.sound nodes 32 checked\n',
             '#print axioms checked\n#print axioms sound\nend ActualPrefix32\n']
    result['ActualPrefix32Sound.lean'] = ''.join(lines)
    return result


def verify_bytes(name, data):
    expected = generate()
    if name not in expected or data != expected[name].encode('utf-8'):
        raise ValueError(f'{name}: generated bytes differ')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for name, text in generate().items():
        path = OUT / name
        expected = text.encode('utf-8')
        if args.check:
            if path.read_bytes() != expected:
                raise SystemExit(f'{name}: generated bytes differ')
        else:
            path.write_bytes(expected)
    print('actual prefix 0..31: generated bytes ' + ('match' if args.check else 'written'))


if __name__ == '__main__':
    main()
