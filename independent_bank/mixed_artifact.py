#!/usr/bin/env python3
"""Compare complete Lean artifact bytes with regeneration from the pinned bank.

This checks reproducibility, not correctness of the generator or a Lean proof of
archive correspondence. It is independent of the semantic round-trip checker.
"""
import argparse
from pathlib import Path

import archive_prefix
import first_shard
import mixed_lean_producer
import mixed_prefix_export


def expected_bytes(kind):
    if kind == 'shard':
        return first_shard.generate().encode('utf-8')
    if kind == 'full':
        doc = mixed_prefix_export.export(archive_prefix.load_bank())
        header = f'/- CLI loaded pinned archive SHA-256 {archive_prefix.SHA256}; transcription is not a provenance proof. -/\n'
        return (header + mixed_lean_producer.render(doc)).encode('utf-8')
    raise ValueError('unknown artifact kind')


def verify(path, kind):
    expected = expected_bytes(kind)
    if Path(path).read_bytes() != expected:
        raise ValueError(f'{kind} artifact differs from regenerated bytes')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('kind', choices=('full', 'shard'))
    parser.add_argument('artifact', type=Path)
    args = parser.parse_args()
    verify(args.artifact, args.kind)
    print(f'{args.kind} artifact matches authenticated archive regeneration byte-for-byte')


if __name__ == '__main__':
    main()
