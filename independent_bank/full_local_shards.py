#!/usr/bin/env python3
"""Generate isolated local-view Lean data shards; experimental, not proofs.

Each shard contains real rules for its interval and support/demand-only records
for all referenced predecessors. Cross-shard semantic assembly is NOT supplied.
"""
import argparse
import collections
import hashlib
import json
import pathlib
import re

import mixed_full_export
import mixed_full_producer
import verify_bank
from bank_interpreter import need

ROOT = pathlib.Path(__file__).resolve().parents[1]


def generate(bank, intervals, target):
    need(type(target) is int and target > 0, 'invalid byte target')
    doc = mixed_full_export.export(bank, intervals)
    ns = doc['nodes']
    text = mixed_full_producer.render(bank, intervals)
    header = 'def nodes : ℕ → MixedDag.Node Payload\n'
    footer = '\n  | _ => ⟨∅, 0, .small⟩\n'
    need(text.count(header) == text.count(footer) == 1, 'data boundaries')
    lines = text.split(header, 1)[1].split(footer, 1)[0].splitlines()
    need(len(lines) == len(ns) == 4106, 'node count')
    for i, (node, line) in enumerate(zip(ns, lines, strict=True)):
        need(node['id'] == i and line.startswith(f'  | {i} => '), 'node ordering')
        for r in node.get('references', []):
            need(type(r['source']) is int and 0 <= r['source'] < i, 'predecessor ordering')
    ranges = []
    start = size = 0
    for i, line in enumerate(lines):
        n = len((line + '\n').encode())
        if i > start and size + n > target:
            ranges.append((start, i)); start = i; size = 0
        size += n
    ranges.append((start, len(lines)))
    common = '''import FullLocalAssemblyCandidate
namespace FullLocalShards
abbrev Payload := FullLocalAssemblyCandidate.Payload
abbrev extraCheck := FullLocalAssemblyCandidate.extraCheck
end FullLocalShards
'''
    files = {'FullLocalCommon.lean': common}
    shards = []
    for serial, (lo, hi) in enumerate(ranges):
        refs = sorted({r['source'] for n in ns[lo:hi] for r in n.get('references', [])} - set(range(lo, hi)))
        arms = {i: lines[i] for i in range(lo, hi)}
        for i in refs:
            n = ns[i]
            arms[i] = f"  | {i} => ⟨{mixed_full_producer.fs(n['support'])}, {n['demand']}, .small⟩"
        name = f'FullLocal{serial:04}.lean'
        contents = ('import FullLocalCommon\n\nnamespace FullLocalShards.S' + str(serial) +
                    '\n/- Candidate data only; predecessor rule fields are synthetic. -/\n'
                    'def nodes : ℕ → MixedDag.Node FullLocalShards.Payload\n' +
                    '\n'.join(arms[i] for i in sorted(arms)) +
                    '\n  | _ => ⟨∅, 0, .small⟩\nend FullLocalShards.S' + str(serial) + '\n')
        files[name] = contents
        shards.append({'file': name, 'start': lo, 'end': hi, 'predecessor_snapshots': len(refs),
                       'bytes': len(contents.encode()), 'sha256': hashlib.sha256(contents.encode()).hexdigest(),
                       'kinds': dict(sorted(collections.Counter(n['kind'] for n in ns[lo:hi]).items()))})
    need([i for s in shards for i in range(s['start'], s['end'])] == list(range(4106)), 'coverage')
    need([n['id'] for n in ns if n['kind'] == 'externalActive'] == [1097, 1107, 1112, 1114], 'external inventory')
    manifest = {'format': 'local-view-shards-v1', 'count': len(ns), 'target_rule_bytes': target,
                'archive_sha256_claim': None, 'external_assumptions': [1097, 1107, 1112, 1114],
                'total_references_occurrences': sum(len(n.get('references', [])) for n in ns),
                'counts': doc['counts'], 'shards': shards}
    return files, manifest


def verify_output(output, files, manifest):
    """Require exact regenerated bytes and inventory; never trust the manifest alone."""
    expected = {name: text.encode('utf8') for name, text in files.items()}
    expected['manifest.json'] = (json.dumps(manifest, indent=2, sort_keys=True) + '\n').encode('utf8')
    need(output.is_dir() and not output.is_symlink(), 'output must be a real directory')
    actual = {entry.name: entry for entry in output.iterdir()}
    need(set(actual) == set(expected), 'output inventory mismatch')
    for name, data in expected.items():
        entry = actual[name]
        need(not entry.is_symlink() and entry.is_file(), f'not a regular file: {name}')
        need(entry.read_bytes() == data, f'output differs from regeneration: {name}')


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('output', type=pathlib.Path)
    p.add_argument('--target-bytes', type=int, default=262144)
    p.add_argument('--verify-existing', action='store_true', help='compare exact inventory and bytes with independent regeneration')
    args = p.parse_args()
    path = ROOT / 'input/erdos302_boundary_certificates_publication.zip'
    bank, intervals = verify_bank.load_archive(path)
    files, manifest = generate(bank, intervals, args.target_bytes)
    manifest['archive_sha256_claim'] = verify_bank.HASH
    if args.verify_existing:
        verify_output(args.output, files, manifest)
    else:
        args.output.mkdir(parents=True, exist_ok=True)
        need(not list(args.output.iterdir()), 'output directory must be empty')
        for name, text in files.items():
            (args.output / name).write_text(text, encoding='utf8')
        (args.output / 'manifest.json').write_text(json.dumps(manifest, indent=2, sort_keys=True) + '\n')
    print(json.dumps({'shards': len(manifest['shards']), 'counts': manifest['counts'],
                      'max_bytes': max(s['bytes'] for s in manifest['shards']),
                      'total_bytes': sum(s['bytes'] for s in manifest['shards']),
                      'references': manifest['total_references_occurrences']}))


if __name__ == '__main__':
    main()
