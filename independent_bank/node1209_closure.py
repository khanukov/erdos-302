#!/usr/bin/env python3
"""Extract actual node 1209 ancestry; generate independent small-node Lean checks.

This first phase does NOT generate/check case, trim, pack or a DAG soundness theorem.
"""
import argparse
import collections
import copy
import json
from pathlib import Path

import archive_prefix
from bank_interpreter import interpret
from verify_bank import small_only

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'audit/node1209-closure'

def references(node):
    t = node['t']
    if t in ('pack', 'qpack'): return [row[0] for row in node['rows']]
    if t == 'case': return list(node['cs'])
    if t == 'trim': return [node['ref']]
    if t == 'small': return []
    raise ValueError('unsupported or external rule: ' + t)

def extract():
    bank = archive_prefix.load_bank()
    nodes, images = bank['nodes'], bank['images']
    pending, seen = [1209], set()
    while pending:
        i = pending.pop()
        if i in seen: continue
        if not 0 <= i < len(nodes): raise ValueError('node index')
        seen.add(i)
        for j in references(nodes[i]):
            if type(j) is not int or not 0 <= j < len(images): raise ValueError('image index')
            source = images[j][0]
            if type(source) is not int or not 0 <= source < i: raise ValueError('non-backward reference')
            pending.append(source)
    order = sorted(seen)
    index = {x: i for i, x in enumerate(order)}
    short, remapped_images, result = [], [], []
    for original in order:
        node = copy.deepcopy(nodes[original])
        ids = references(node)
        refs = []
        for image_id in ids:
            source, mul, div = images[image_id]
            refs.append({'image': image_id, 'original_source': source, 'dense_source': index[source], 'mul': mul, 'div': div})
            remapped_images.append([index[source], mul, div])
        first = len(remapped_images) - len(ids)
        if node['t'] in ('pack', 'qpack'):
            for k, row in enumerate(node['rows']): row[0] = first + k
        elif node['t'] == 'case': node['cs'] = list(range(first, first + len(ids)))
        elif node['t'] == 'trim': node['ref'] = first
        short.append(node)
        result.append({'original': original, 'raw_node': nodes[original], 'references': refs})
    counts = collections.Counter(n['raw_node']['t'] for n in result)
    if len(order) != 376 or counts != {'small': 368, 'case': 4, 'trim': 3, 'pack': 1} or len(remapped_images) != 1056:
        raise ValueError('unexpected closure inventory')
    values = interpret(short, remapped_images, small_only)
    for record, (support, demand) in zip(result, values):
        record['support'] = list(support)
        record['demand'] = demand
    if result[-1]['original'] != 1209 or len(result[-1]['references']) != 510 or len(values[-1][0]) != 901 or values[-1][1] != 258:
        raise ValueError('unexpected root')
    return {'format': 'node1209-induced-closure-v1', 'bank_sha256': archive_prefix.SHA256, 'nodes': result}

def generate():
    doc = extract()
    files = {'closure.json': json.dumps(doc, sort_keys=True, indent=2) + '\n'}
    small = [n for n in doc['nodes'] if n['raw_node']['t'] == 'small']
    for shard in range((len(small) + 15) // 16):
        batch = small[shard*16:shard*16+16]
        lines = ['import Dag\n', '\nnamespace Node1209Small\n', 'set_option maxRecDepth 4096\n', 'set_option maxHeartbeats 4000000\n']
        for n in batch:
            support = '{' + ', '.join(map(str, n['support'])) + '}'
            lines.append(f"theorem node{n['original']} : ArchiveDag.SmallCheck {support} {n['demand']} := by decide\n")
            lines.append(f"#print axioms node{n['original']}\n")
        lines.append('end Node1209Small\n')
        files[f'Small{shard:02}.lean'] = ''.join(lines)
    return files

def verify():
    expected = generate()
    actual = {p.name for p in OUT.iterdir() if p.name == 'closure.json' or p.name.startswith('Small') and p.suffix == '.lean'}
    if actual != set(expected): raise ValueError('generated inventory mismatch')
    for name, text in expected.items():
        if (OUT / name).read_bytes() != text.encode(): raise ValueError('generated bytes mismatch: ' + name)

def main():
    p = argparse.ArgumentParser()
    p.add_argument('--check', action='store_true')
    args = p.parse_args()
    if args.check: verify()
    else:
        OUT.mkdir(parents=True, exist_ok=True)
        for name, text in generate().items(): (OUT / name).write_text(text)
        verify()
    print('PASS pinned closure extraction, occurrence remapping, replay and small-shard bytes')

if __name__ == '__main__': main()
