#!/usr/bin/env python3
"""Generate kernel capacity candidates over all original occurrence row objects.

Run after node1209_pack_all --check. The data references the row shards directly;
Python never supplies a precomputed incidence table to the Lean theorem.
"""
from pathlib import Path
import sys
import node1209_closure
import node1209_pack_all
import node1209_pack_preflight

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'lean/node1209-capacity'
SIZE = 10

def lit(xs):
    return '{' + ', '.join(map(str, xs)) + '}'

def generate():
    doc = node1209_closure.extract()
    node1209_pack_preflight.check(doc)
    data = node1209_pack_all.generate()
    rows = data['rows']
    vertices = doc['nodes'][-1]['support']
    if len(rows) != 510 or len(vertices) != 901:
        raise ValueError('unexpected dimensions')
    imports = [f'import Node1209Rows{i:03d}' for i in range(64)]
    lines = imports + ['open Finset UpperBridge', 'namespace Node1209CapacityData',
        'set_option maxRecDepth 65536', 'set_option maxHeartbeats 100000000',
        'def target : Finset ℕ := Node1209Rows000.target',
        '-- One list entry per original occurrence, including duplicates.',
        'def rows : List (Finset ℕ × ℕ) := [']
    for i in range(510):
        n = f'Node1209Rows{i//8:03d}'
        lines.append(f'  (ArchiveScaling.image {n}.source{i} {n}.row{i}.mul {n}.row{i}.div, {n}.row{i}.weight)' + (',' if i < 509 else ''))
    lines += [']', 'def load (x : ℕ) : ℕ :=',
              '  (rows.map (fun r => if x ∈ r.1 then r.2 else 0)).sum',
              'end Node1209CapacityData', '']
    files = {'Node1209CapacityData.lean': '\n'.join(lines).encode()}
    chunks = [vertices[i:i+SIZE] for i in range(0, len(vertices), SIZE)]
    for b, chunk in enumerate(chunks):
        name = f'Node1209Capacity{b:03d}'
        lines = ['import Node1209CapacityData', 'open Finset Node1209CapacityData',
                 f'namespace {name}', 'set_option maxRecDepth 65536',
                 'set_option maxHeartbeats 100000000', f'def vertices : Finset ℕ := {lit(chunk)}']
        for v in chunk:
            lines += [f'theorem vertex{v} : load {v} ≤ 1001 := by decide', f'#print axioms vertex{v}']
        lines += ['theorem capacity : ∀ x ∈ vertices, load x ≤ 1001 := by',
                  '  intro x hx', '  simp only [vertices, Finset.mem_insert, Finset.mem_singleton] at hx',
                  '  rcases hx with ' + ' | '.join('rfl' for _ in chunk)]
        lines += [f'  · exact vertex{v}' for v in chunk]
        lines += ['#print axioms capacity', f'end {name}', '']
        files[name+'.lean'] = '\n'.join(lines).encode()
    names = [f'Node1209Capacity{b:03d}' for b in range(len(chunks))]
    union = f'{names[-1]}.vertices'
    for n in reversed(names[:-1]):
        union = f'{n}.vertices ∪ ({union})'
    lines = [f'import {n}' for n in names] + ['open Finset Node1209CapacityData',
       'namespace Node1209CapacityAll', 'set_option maxRecDepth 65536',
       'set_option maxHeartbeats 100000000',
       f'theorem coverage : target ⊆ ({union}) := by decide',
       'theorem capacity : ∀ x ∈ target, load x ≤ 1001 := by',
       '  intro x hx', '  have h := coverage hx',
       '  simp only [Finset.mem_union] at h',
       '  rcases h with ' + ' | '.join(f'h{i}' for i in range(len(names)))]
    lines += [f'  · exact {n}.capacity x h{i}' for i,n in enumerate(names)]
    lines += ['#print axioms coverage', '#print axioms capacity', 'end Node1209CapacityAll', '']
    files['Node1209CapacityAll.lean'] = '\n'.join(lines).encode()
    return files

def check_files(expected, actual):
    if actual != expected:
        raise ValueError('capacity file inventory or generated bytes differ')

def main():
    node1209_closure.verify()
    expected_rows = node1209_pack_all.generate()
    node1209_pack_all.check_files(expected_rows, {p.name:p.read_bytes() for p in node1209_pack_all.OUT.glob('*.lean')})
    files = generate()
    if sys.argv[1:] == ['--write']:
        OUT.mkdir(parents=True, exist_ok=True)
        for name, content in files.items():
            (OUT / name).write_bytes(content)
    elif sys.argv[1:] == ['--check']:
        actual = {p.name:p.read_bytes() for p in OUT.glob('*.lean')}
        check_files(files, actual)
    else:
        raise SystemExit('use --write or --check')
    print('510 occurrence references; 901 vertex checks; 91 shards; one assembly')

if __name__ == '__main__':
    main()
